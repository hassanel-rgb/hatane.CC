#include "libft.h"

char	*ft_strtrim(char const *s1, char const *set)
{
	char	*p;
	size_t	start;
	size_t	end;
	size_t	total;

	if (!s1 || !set)
		return (NULL);
	start = 0;
	end = ft_strlen(s1);
	while (s1[start] && ft_strchr(set, s1[start]))
		start++;
	while (end > start && ft_strchr(set, s1[end - 1]))
		end--;
	total = end - start;
	p = malloc(total + 1);
	if (!p)
		return (NULL);
	ft_memcpy(p, s1 + start, total);
	p[total] = '\0';
	return (p);
}
