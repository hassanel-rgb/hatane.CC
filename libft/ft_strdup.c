#include "libft.h"

char	*ft_strdup(const char *s)
{
	char *ptr;
	size_t i;

	i = 0;
	while (s[i])
		i++;
	ptr = malloc(i + 1);
	if (ptr == NULL)
		return (0);
	i = 0;
	while (s[i])
	{
		ptr[i] = s[i];
		i++;
	}
	ptr[i] = '\0';
	return (ptr);
}
