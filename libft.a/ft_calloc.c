#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	void *ptr;
	if ((nmemb * size) > (size_t) - 1)
		return (NULL);
	if (nmemb == 0 || size == 0)
		return (malloc(0));
	ptr = malloc(nmemb * size);
	if (!ptr)
		return (NULL);
	ft_bzero(ptr, nmemb);
	return (ptr);
}
int main(){
	char *p = ft_calloc(18446744073709551615,1);
	printf("%s\n", p);
	return 0;
}
