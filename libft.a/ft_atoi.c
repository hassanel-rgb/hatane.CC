#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		i;
	int		s;
	size_t	r;

	i = 0;
	s = 1;
	r = 0;
	while (nptr[i] == 32 || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '+' || nptr[i] == '-')
	{
		if (nptr[i] == '-')
			s *= -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		r = r * 10 + (nptr[i] - '0');
		if (r > 9223372036854775807ULL && s == 1)
			return (-1);
		if (r > 9223372036854775807ULL && s == -1)
			return (0);
		i++;
	}
	return (r * s);
}
